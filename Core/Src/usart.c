Data_StatusTypeDef Data_Verify(uint8_t *data, uint16_t total_length)
{
  // check null
  if (data == NULL)
  {
    return NULL_PTR_ERROR;
  }

  // check minimum length (header + length + command + checksum)
  if (total_length < 4)
  {
    return LENGTH_ERROR;
  }

  // check header
  if (data[HEADER_INDEX] != PACKET_HEADER)
  {
    return HEADER_ERROR;
  }

  // check length
  uint8_t expected_payload_len = data[LENGTH_INDEX];
  if (total_length != (2 + expected_payload_len))
  {
    return LENGTH_ERROR;
  }

  CMD_TypeDef command = (CMD_TypeDef)data[CMD_INDEX];

  if (command != SPI_WRITE &&
      command != SPI_READ_SINGLE &&
      command != SPI_RESET &&
      command != SPI_READ_MULTIPLE &&
      command != SPI_WRITE_MULTIPLE &&
      command != TAG_TYPE_A_WRITE &&
      command != TAG_TYPE_A_READ &&
      command != TAG_TYPE_A_DUMP &&
      command != TAG_TYPE_A_READ_UID)
  {
    return CMD_ERROR;
  }

  // check checksum (BCC)
  uint8_t bcc_check = 0;
  for (uint16_t i = 0; i < total_length; i++)
  {
    bcc_check ^= data[i];
  }

  if (bcc_check != 0)
  {
    return CHECKSUM_ERROR;
  }

  return CHECKSUM_OK;
}

void Response(uint8_t *data, uint8_t data_len)
{
  uint8_t response_buffer[50];
  memset(response_buffer, 0x00, 50);
  response_buffer[HEADER_INDEX] = PACKET_HEADER;
  response_buffer[LENGTH_INDEX] = data_len + 1; // Payload length + checksum
  for (uint8_t i = 0; i < data_len; i++)
  {
    response_buffer[2 + i] = data[i];
  }
  // Calculate checksum
  uint8_t checksum = 0;
  for (int i = 0; i <= strlen((char *)response_buffer); i++)
  {
    checksum ^= response_buffer[i];
  }
  response_buffer[2 + data_len] = checksum;
  HAL_UART_Transmit(&huart2, response_buffer, 3 + data_len, 100);
}
